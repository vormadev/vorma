	#[test]
	fn generated_contracts_hold_formatting_invariants_for_all_input_combinations() {
		// Names register intentionally out of alphabetical order so the
		// sorted-output invariant is exercised, not satisfied by accident.
		let def_levels: Vec<(&str, Vec<TypeDef>)> = vec![
			("no defs", Vec::new()),
			("one record", vec![record_def("ZzRecord")]),
			(
				"record + alias + enum",
				vec![
					record_def("ZzRecord"),
					TypeDef::Alias {
						key: "MmAlias".to_owned(),
						name: "MmAlias".to_owned(),
						target: TypeRefContract::String,
					},
					TypeDef::StringEnum {
						key: "AaEnum".to_owned(),
						name: "AaEnum".to_owned(),
						variants: vec!["asc".to_owned(), "desc".to_owned()],
					},
				],
			),
			(
				"record + alias + enum + raw",
				vec![
					record_def("ZzRecord"),
					TypeDef::Alias {
						key: "MmAlias".to_owned(),
						name: "MmAlias".to_owned(),
						target: TypeRefContract::String,
					},
					TypeDef::StringEnum {
						key: "AaEnum".to_owned(),
						name: "AaEnum".to_owned(),
						variants: vec!["asc".to_owned(), "desc".to_owned()],
					},
					TypeDef::Raw {
						key: "RrRaw".to_owned(),
						name: "RrRaw".to_owned(),
						body: vec![RawTsPart::Text("string | number".to_owned())],
					},
				],
			),
		];
		let view_levels: Vec<(&str, Vec<ViewDeclaration>)> = vec![
			("no views", Vec::new()),
			(
				"one view",
				vec![ViewDeclaration::new(
					"/",
					"root.tsx",
					serde_json::json!({}),
					RouteTypeContract::new(TypeRefContract::Unit, TypeRefContract::Null),
					handler_id("root"),
				)],
			),
			(
				"params + splat views",
				vec![
					ViewDeclaration::new(
						"/",
						"root.tsx",
						serde_json::json!({}),
						RouteTypeContract::new(TypeRefContract::Unit, TypeRefContract::Null),
						handler_id("root"),
					),
					ViewDeclaration::new(
						"/users/:id",
						"user.tsx",
						serde_json::json!({"q": "string"}),
						RouteTypeContract::new(TypeRefContract::Unit, TypeRefContract::Null),
						handler_id("user"),
					),
					ViewDeclaration::new(
						"/files/*",
						"files.tsx",
						serde_json::json!({}),
						RouteTypeContract::new(TypeRefContract::Unit, TypeRefContract::Null),
						handler_id("files"),
					),
				],
			),
		];
		let resource_levels: Vec<(&str, Vec<ResourceDeclaration>)> = vec![
			("no resources", Vec::new()),
			(
				"one query resource",
				vec![ResourceDeclaration::new(
					Method::GET,
					"/ping",
					None,
					None,
					RouteTypeContract::new(TypeRefContract::Unit, TypeRefContract::Null),
					handler_id("ping"),
				)],
			),
			(
				"query + mutation resources",
				vec![
					ResourceDeclaration::new(
						Method::GET,
						"/ping",
						None,
						None,
						RouteTypeContract::new(TypeRefContract::Unit, TypeRefContract::Null),
						handler_id("ping"),
					),
					ResourceDeclaration::new(
						Method::POST,
						"/things",
						None,
						None,
						RouteTypeContract::new(TypeRefContract::Unit, TypeRefContract::Null),
						handler_id("things"),
					),
				],
			),
			(
				"form-data resource",
				vec![ResourceDeclaration::new(
					Method::POST,
					"/upload",
					None,
					None,
					RouteTypeContract::new(TypeRefContract::FormData, TypeRefContract::Null),
					handler_id("upload"),
				)],
			),
		];
		let filemap_levels: Vec<(&str, BTreeMap<String, String>)> = vec![
			("no assets", BTreeMap::new()),
			(
				"one asset",
				BTreeMap::from([("app.css".to_owned(), "/static/app.h.css".to_owned())]),
			),
			(
				"three assets",
				BTreeMap::from([
					("app.css".to_owned(), "/static/app.h.css".to_owned()),
					("logo.svg".to_owned(), "/static/logo.h.svg".to_owned()),
					("font.woff2".to_owned(), "/static/font.h.woff2".to_owned()),
				]),
			),
		];
		let extra_levels: Vec<(&str, Option<&str>)> = vec![
			("no extra source", None),
			(
				"extra source with newline",
				Some("export const extra = 1;\n"),
			),
			(
				"extra source without newline",
				Some("export const extra = 1;"),
			),
		];

		let mut combinations = 0;
		for (def_label, defs) in &def_levels {
			for (view_label, views) in &view_levels {
				for (resource_label, resources) in &resource_levels {
					for (filemap_label, filemap) in &filemap_levels {
						for (extra_label, extra) in &extra_levels {
							combinations += 1;
							let label = format!(
								"{def_label} / {view_label} / {resource_label} / {filemap_label} / {extra_label}"
							);
							let build = || {
								let mut declarations = match extra {
									Some(extra) => FrameworkDeclarations::new(
										FrameworkConfig::new("/static/").with_build_inputs(
											BuildInputConfig::new(
												ServerBuildTarget::new("pkg", "bin"),
												"/tmp/app",
												"dist",
												FrontendBuildInputs::new(
													"react",
													"pnpm",
													".",
													"vite.config.ts",
													"src/entry.tsx",
													"public",
													"src/critical.css",
												),
												"src/vorma.gen.ts",
												DevWatchConfig::default(),
											)
											.with_generated_typescript_extra_source(*extra),
										),
									),
									None => FrameworkDeclarations::default(),
								};
								for def in defs {
									declarations.add_type_def(def.clone());
								}
								for view in views {
									declarations.add_view(view.clone());
								}
								for resource in resources {
									declarations.add_resource(resource.clone());
								}
								let graph = FrameworkGraph::compile(declarations)
									.unwrap_or_else(|error| panic!("{label}: {error:?}"));
								render_typescript_contracts(
									&ProjectionBundle::compile(&graph),
									filemap,
								)
								.unwrap_or_else(|error| panic!("{label}: {error}"))
							};

							let first = build();
							let second = build();
							assert_eq!(
								first.source(),
								second.source(),
								"{label}: nondeterministic output"
							);

							let source = first.source();
							assert!(
								source.starts_with(GENERATED_HEADER),
								"{label}: missing header"
							);
							assert!(
								!source.contains("\n\n\n"),
								"{label}: double blank line\n{source}"
							);
							assert!(source.ends_with('\n'), "{label}: missing trailing newline");
							assert!(
								!source.ends_with("\n\n"),
								"{label}: trailing blank line\n{source}"
							);
							assert!(
								!source.contains(" \n") && !source.contains("\t\n"),
								"{label}: trailing whitespace\n{source}"
							);

							let mut def_positions = Vec::new();
							for def in sorted_type_defs(defs) {
								let needle = format!("export type {} = ", def.name());
								let position = source.find(&needle).unwrap_or_else(|| {
									panic!("{label}: missing def {}\n{source}", def.name())
								});
								def_positions.push(position);
							}
							assert!(
								def_positions.is_sorted(),
								"{label}: type defs out of order\n{source}"
							);
						}
					}
				}
			}
		}
		assert_eq!(combinations, 432);
	}
